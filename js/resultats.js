let tableauResultats =
    document.getElementById("table-resultats");

    if (tableauResultats) {
    tableauResultats.innerHTML = `
        <tr>
            <th>Match</th>
            <th>Date</th>
            <th>Heure</th>
            <th>Compétition</th>
            <th>Statut</th>
            <th>Résultat</th>
        </tr>
    `;
}

if (tableauResultats) {

    supabaseClient
        .from("matchs")
        .select("*")

        .then(function(resultatSupabase) {

            if (resultatSupabase.error) {

                console.error(
                    "❌ Erreur chargement des matchs depuis Supabase :",
                    resultatSupabase.error
                );

                throw resultatSupabase.error;

            }

            let matchsAdmin =
                resultatSupabase.data || [];

            console.log(
                "✅ Résultats chargés depuis Supabase :",
                matchsAdmin.length
            );

            // ==========================================
           // TRIER LES MATCHS DU PLUS RÉCENT AU PLUS ANCIEN
          // ==========================================

matchsAdmin.sort(function(a, b) {

    let dateA =
        new Date(a.date + "T" + a.heure);

    let dateB =
        new Date(b.date + "T" + b.heure);

    return dateB - dateA;

});

           console.log(
    "✅ Résultats chargés depuis Supabase :",
    matchsAdmin.length
);

            // ==========================================
            // AFFICHER LES MATCHS
            // ==========================================

            matchsAdmin.forEach(function(match) {

                console.log(
                    "MATCH RESULTAT :",
                    match.equipe1,
                    "-",
                    match.equipe2,
                    match.score1,
                    "-",
                    match.score2
                );

                let equipe1 =
                    match.equipe1.trim();

                let equipe2 =
                    match.equipe2.trim();


                // ==========================================
                // LOGO / DRAPEAU ÉQUIPE 1
                // ==========================================

               let imageEquipe1 =
                   logosJupilerProLeagueResultats[equipe1] ||
                   logosChampionsLeagueResultats[equipe1] ||
                   logosEuropaLeagueResultats[equipe1] ||
                   drapeauxPaysResultats[equipe1];

                let affichageEquipe1 =
                    imageEquipe1

                    ? `<img src="${imageEquipe1}"
                        style="width:35px;height:35px;object-fit:contain;vertical-align:middle;margin-right:8px;">
                       ${equipe1}`

                    : equipe1;


                // ==========================================
                // LOGO / DRAPEAU ÉQUIPE 2
                // ==========================================

                let imageEquipe2 =
                    logosJupilerProLeagueResultats[equipe2] ||
                    logosChampionsLeagueResultats[equipe2] ||
                    logosEuropaLeagueResultats[equipe2] ||
                    drapeauxPaysResultats[equipe2];


                let affichageEquipe2 =
                    imageEquipe2

                    ? `<img src="${imageEquipe2}"
                        style="width:35px;height:35px;object-fit:contain;vertical-align:middle;margin-right:8px;">
                       ${equipe2}`

                    : equipe2;


                // ==========================================
                // RÉSULTAT
                // ==========================================

                let resultat =
                    "⚽ À venir";

                let vainqueur = "";


                if (match.statut === "Terminé") {

                    resultat =
                        match.score1 +
                        " - " +
                        match.score2;


                    if (
                        Number(match.score1) >
                        Number(match.score2)
                    ) {

                        vainqueur =
                            " 🏆 Victoire " +
                            equipe1;

                    }

                    else if (
                        Number(match.score1) <
                        Number(match.score2)
                    ) {

                        vainqueur =
                            " 🏆 Victoire " +
                            equipe2;

                    }

                    else {

                        vainqueur =
                            " 🤝 Match nul";

                    }

                }

                else if (
                    match.statut === "En cours"
                ) {

                    resultat =
                        "🔴 Match en cours";

                }


                // ==========================================
                // AJOUTER LA LIGNE AU TABLEAU
                // ==========================================

                tableauResultats.innerHTML +=

                    "<tr>" +

                    "<td>" +
                    affichageEquipe1 +
                    " 🆚 " +
                    affichageEquipe2 +
                    "</td>" +

                    "<td>" +
                    match.date +
                    "</td>" +

                    "<td>" +
                    match.heure +
                    "</td>" +

                    "<td>" +
                    afficherCompetition(
                        match.competition
                    ) +
                    "</td>" +

                    "<td>" +
                    match.statut +
                    "</td>" +

                    "<td>" +
                    "⚽ " +
                    resultat +
                    vainqueur +
                    "</td>" +

                    "</tr>";

            });

        })

        .catch(function(erreur) {

            console.error(
                "❌ Impossible de charger les résultats :",
                erreur
            );

        });

}

function afficherCompetition(competition) {

    if (competition === "Ligue des Nations") {
        return "🏆🇪🇺 Ligue des Nations";
    }

    if (competition === "Coupe du Monde") {
        return "🌍 Coupe du Monde";
    }

    if (competition === "Euro") {
        return "🏆 Euro";
    }

    if (competition === "Ligue des Champions") {
        return "⭐ Ligue des Champions";
    }

    return competition;

}