// ==========================================
// NETTOYAGE DU NOM DE L'ÉQUIPE
// ==========================================

function nettoyerNomEquipe(nom) {

    return nom
        .replace(/🇧🇪|🇮🇹|🇫🇷|🇹🇷|🇪🇸/g, "")
        .trim();

}


// ==========================================
// TROUVER L'IMAGE DE L'ÉQUIPE
// ==========================================

function trouverImageEquipe(nomEquipe, imageParDefaut) {

    let nom = nettoyerNomEquipe(nomEquipe);

    return (
        logosClubs[nom] ||
        drapeauxEquipes[nom] ||
        imageParDefaut
    );

} 